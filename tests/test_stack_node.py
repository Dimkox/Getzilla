class LockfileTests(unittest.TestCase):
    def test_osv_reads_pnpm_and_yarn_lockfiles(self) -> None:
        self.assertEqual(sorted(_pairs_from_pnpm_lock(PNPM_V9)),
                         [('@babel/core', '7.24.0'), ('lodash', '4.17.20'), ('react-dom', '18.3.1')])
        self.assertEqual(sorted(_pairs_from_pnpm_lock(PNPM_V6)), [('@types/node', '20.11.5'), ('left-pad', '1.3.0')])
        self.assertEqual(sorted(_pairs_from_yarn_lock(YARN_CLASSIC)), [('@babel/code-frame', '7.23.5'), ('lodash', '4.17.20')])
        self.assertEqual(list(_pairs_from_yarn_lock(YARN_BERRY)), [('lodash', '4.17.20')])

    def test_lockfile_picks_the_manager_and_the_install(self) -> None:
        with tempfile.TemporaryDirectory() as tmp:
            root = Path(tmp)
            self.assertEqual(verification.node_lockfile(root), ('npm', None))
            cases = (('package-lock.json', '{}', ['npm', 'ci']),
                     ('pnpm-lock.yaml', PNPM_V9, ['pnpm', 'install', '--frozen-lockfile']),
                     ('yarn.lock', YARN_CLASSIC, ['yarn', 'install', '--frozen-lockfile']),
                     ('yarn.lock', YARN_BERRY, ['yarn', 'install', '--immutable']))
            with mock.patch.object(verification, 'command_exists', return_value=True):
                for name, text, command in cases:
                    with self.subTest(lockfile=name, command=command[-1]):
                        for old in root.iterdir():
                            old.unlink()
                        (root / name).write_text(text, encoding='utf-8')
                        manager, lockfile = verification.node_lockfile(root)
                        self.assertEqual(verification._node_install_command(root, manager, lockfile), command)
            with mock.patch.object(verification, 'command_exists', side_effect=lambda name: name == 'npm'):
                self.assertEqual(verification._node_install_command(root, 'yarn', 'yarn.lock')[:2], ['corepack', 'yarn'])


class NodeChecksTests(unittest.TestCase):
    def setUp(self) -> None:
        tmp = tempfile.TemporaryDirectory()
        self.addCleanup(tmp.cleanup)
        self.root = Path(tmp.name)
        (self.root / 'package.json').write_text(json.dumps({'scripts': {'lint': 'eslint .', 'test': 'vitest'}}), encoding='utf-8')
        self.calls: list[tuple[list[str], dict[str, str]]] = []

    def _execute(self, command, cwd, environment, **_kwargs):
        self.calls.append((list(command), dict(environment)))
        return ProcessResult(command, 0)

    def _run(self, mode: str, *, npm: bool = True, toolchain=None) -> list:
        patches = [mock.patch.object(verification, 'execute', side_effect=self._execute),
                   mock.patch.object(verification, 'command_exists', return_value=npm),
                   mock.patch.object(verification, 'resolve_command', side_effect=lambda command, _path: command)]
        if toolchain is not None:
            patches.append(mock.patch.object(verification, 'ensure_toolchain', return_value=toolchain))
        for item in patches:
            item.start()
            self.addCleanup(item.stop)
        return verification._node(self.root, mode, keep_going=True)

    def test_pr_without_a_lockfile_is_refused(self) -> None:
        results = self._run('pr')
        lock = next(check for check in results if check.name == 'node-lockfile')
        self.assertEqual((lock.status, lock.summary), ('fail', 'NODE_LOCK_MISSING'))

    def test_pr_installs_from_the_lockfile_before_scripts(self) -> None:
        (self.root / 'package-lock.json').write_text('{"lockfileVersion": 3, "packages": {}}', encoding='utf-8')
        results = self._run('pr')
        self.assertEqual([check.name for check in results], ['npm-install', 'npm-lint', 'npm-test'])
        self.assertEqual(self.calls[0][0], ['npm', 'ci'])

    def test_missing_npm_delivers_the_pinned_toolchain(self) -> None:
        home = self.root / 'tc'
        toolchain = Toolchain('node', '24.22.0', home, (home / 'bin',), {})
        (self.root / 'package-lock.json').write_text('{}', encoding='utf-8')
        results = self._run('pr', npm=False, toolchain=toolchain)
        self.assertEqual([check.status for check in results], ['pass', 'pass', 'pass'])
        self.assertTrue(all(env['PATH'].startswith(str(home / 'bin')) for _command, env in self.calls))

    def test_missing_npm_without_a_toolchain_fails_with_the_reason(self) -> None:
        results = self._run('fast', npm=False, toolchain=Blocker('TOOLCHAIN_UNAVAILABLE', 'offline'))
        self.assertEqual([(check.name, check.status, check.summary) for check in results],
                         [('node-tooling', 'fail', 'TOOLCHAIN_UNAVAILABLE')])

    def test_tsconfig_without_typecheck_script_runs_tsc_or_says_why_not(self) -> None:
        (self.root / 'package-lock.json').write_text('{}', encoding='utf-8')
        (self.root / 'tsconfig.json').write_text('{}', encoding='utf-8')
        results = self._run('pr')
        tsc = next(check for check in results if check.name == 'tsc')
        self.assertEqual((tsc.status, tsc.details[0]['code']), ('fail', 'TYPESCRIPT_NOT_INSTALLED'))
        binary = self.root / 'node_modules' / '.bin' / ('tsc.cmd' if os.name == 'nt' else 'tsc')
        binary.parent.mkdir(parents=True)
        binary.write_text('', encoding='utf-8')
        self.calls.clear()
        results = verification._node(self.root, 'pr', keep_going=True)
        self.assertEqual(next(check for check in results if check.name == 'tsc').status, 'pass')
        self.assertEqual(self.calls[-1][0], [str(binary), '--noEmit'])


@unittest.skipUnless(os.environ.get('GETZILLA_E2E_TOOLCHAINS') == '1', 'downloads Node from nodejs.org')
class NodeToolchainEndToEnd(unittest.TestCase):
    def test_real_node_download_is_verified_and_runs(self) -> None:
        spec = load_registry(ROOT)['node'].toolchain
        with tempfile.TemporaryDirectory() as tmp, mock.patch.dict(os.environ, {'GETZILLA_TOOLCHAIN_CACHE': str(Path(tmp) / 'cache')}):
            toolchain = ensure_toolchain('node', spec, spec['default_version'], root=Path(tmp) / 'toolchains')
            self.assertIsInstance(toolchain, Toolchain, toolchain)
            assert isinstance(toolchain, Toolchain)
            out = subprocess.run(['node', '--version'], env=toolchain.process_env(), capture_output=True, text=True, check=True)
            self.assertEqual(out.stdout.strip(), 'v' + spec['default_version'])
            again = ensure_toolchain('node', spec, spec['default_version'], root=Path(tmp) / 'toolchains')
            self.assertFalse(getattr(again, 'fetched', True))


