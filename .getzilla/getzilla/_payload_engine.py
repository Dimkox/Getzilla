"""Canonical stdlib payload primitives; no authority or runtime interception.

The Factory layout is generated byte-identically by getzilla_harness.py.
Edit this canonical Core source, never its Factory mirror.
"""
from __future__ import annotations

import bisect
import json
import math
import re
import time
from typing import Any


class PayloadError(ValueError):
    """A fixed rule code; no payload or exception details."""
    def __init__(self, code: str):
        self.code = code
        super().__init__(code)


def check_deadline(deadline: float) -> None:
    if (type(deadline) not in (int, float) or not math.isfinite(deadline)
            or time.monotonic() >= deadline):
        raise PayloadError('budget_exceeded')


def collect(chunks, *, max_bytes: int, max_chunks: int, deadline: float) -> bytes:
    """Bound each copy; never expose a prefix or suppress cancellation.

    The owned producer must itself have bounded reads. This cannot preempt an
    arbitrary blocked Python iterator and does not qualify a native channel.
    """
    check_deadline(deadline)
    buffered = bytearray()
    try:
        for index, chunk in enumerate(chunks):
            check_deadline(deadline)
            if index >= max_chunks:
                raise PayloadError('chunk_limit')
            if type(chunk) is not bytes:
                raise PayloadError('invalid_chunk')
            if len(chunk) > max_bytes - len(buffered):
                raise PayloadError('input_too_large')
            buffered.extend(chunk)
    except PayloadError:
        raise
    except Exception:
        raise PayloadError('stream_failure') from None
    check_deadline(deadline)
    return bytes(buffered)


def encode_json(value, *, max_bytes: int) -> bytes:
    """Count exact UTF-8 JSON size before allocating an encoded result."""
    remaining = max_bytes

    def charge(size):
        nonlocal remaining
        if size > remaining:
            raise PayloadError('output_too_large')
        remaining -= size

    def quoted(text):
        charge(2)
        for char in text:
            code = ord(char)
            if char in {'"', '\\', '\b', '\f', '\n', '\r', '\t'}:
                charge(2)
            elif code < 32:
                charge(6)
            else:
                charge(len(char.encode('utf-8')))

    def count(item):
        if isinstance(item, dict):
            charge(2 + max(0, len(item) - 1))
            for key, child in item.items():
                quoted(key)
                charge(1)
                count(child)
        elif isinstance(item, list):
            charge(2 + max(0, len(item) - 1))
            for child in item:
                count(child)
        elif isinstance(item, str):
            quoted(item)
        elif item is None:
            charge(4)
        elif type(item) is bool:
            charge(4 if item else 5)
        elif type(item) in (int, float):
            charge(len(json.dumps(item, allow_nan=False)))
        else:
            raise PayloadError('malformed_payload')

    count(value)
    return json.dumps(value, sort_keys=True, ensure_ascii=False, allow_nan=False,
                      separators=(',', ':')).encode('utf-8')


_PEM_BEGIN = re.compile(r"-----BEGIN ([A-Z0-9 ]*PRIVATE KEY)-----")
_PEM_END = re.compile(r"-----END ([A-Z0-9 ]*PRIVATE KEY)-----")
_PEM_MARKER = re.compile(r"-----(?:BEGIN|END) [A-Z0-9 ]*PRIVATE KEY-----")
_BEARER = re.compile(r"(?i)\bBearer[ \t]+[A-Za-z0-9._~+/=-]+")
_AUTHORIZATION = re.compile(
    r"(?im)(?<![A-Za-z0-9_-])(?:[A-Za-z0-9]+[_-])*Authorization"
    r"[ \t]*[=:][ \t]*[^\r\n]*"
)
_SECRET = re.compile(
    r"(?i)(?:sk-|ghp_|github_pat_)[A-Za-z0-9_-]+"
    r"|\b(?:AKIA|ASIA)[A-Z0-9]{16}\b"
    r"|(?<![A-Za-z0-9_-])(?:[\"'])?(?:[a-z0-9]+[_-])*(?:api[_-]?key|"
    r"access[_-]?token|session[_-]?token|client[_-]?secret|refresh[_-]?token|"
    r"password|credential|secret[_-]?key|private[_-]?key|token|secret)"
    r"(?:[_-][a-z0-9]+)*(?:[\"'])?(?![A-Za-z0-9_-])"
    r"[ \t]*[:=][ \t]*(?:\"[^\"\r\n]+\"|'[^'\r\n]+'|[^\s,;}]+)"
)

def redact_pem_blocks(value: str) -> str:
    # One pass per marker kind: a backreferenced lazy regex is quadratic on
    # many BEGIN markers without an END.
    ends: dict[str, list[int]] = {}
    spans: dict[str, list[int]] = {}
    for match in _PEM_END.finditer(value):
        ends.setdefault(match.group(1), []).append(match.start())
        spans.setdefault(match.group(1), []).append(match.end())
    parts: list[str] = []
    position = 0
    for begin in _PEM_BEGIN.finditer(value):
        if begin.start() < position:
            continue
        starts = ends.get(begin.group(1), [])
        index = bisect.bisect_left(starts, begin.end())
        if index == len(starts):
            continue
        parts.append(value[position:begin.start()])
        parts.append("[REDACTED]")
        position = spans[begin.group(1)][index]
    parts.append(value[position:])
    return "".join(parts)


def _replace_bounded(pattern, value: str, max_bytes: int) -> str:
    parts, position, used = [], 0, 0
    for match in pattern.finditer(value):
        piece = value[position:match.start()]
        used += len(piece.encode('utf-8')) + 10  # exact bytes of [REDACTED]
        if used > max_bytes:
            raise PayloadError('output_too_large')
        parts.extend((piece, '[REDACTED]'))
        position = match.end()
    tail = value[position:]
    if len(tail.encode('utf-8')) > max_bytes - used:
        raise PayloadError('output_too_large')
    parts.append(tail)
    return ''.join(parts)


def redact(value: str, max_bytes: int, *, bound_intermediate: bool = False) -> str:
    if not isinstance(value, str):
        raise PayloadError("invalid_text")
    try:
        raw = value.encode("utf-8")
    except UnicodeEncodeError as exc:
        raise PayloadError("invalid_text") from exc
    if len(raw) > max_bytes:
        raise PayloadError("text_too_large")
    redacted = redact_pem_blocks(value)
    if _PEM_MARKER.search(redacted):
        raise PayloadError("secret_content")
    for pattern in (_AUTHORIZATION, _BEARER, _SECRET):
        redacted = (_replace_bounded(pattern, redacted, max_bytes) if bound_intermediate
                    else pattern.sub("[REDACTED]", redacted))
    if len(redacted.encode("utf-8")) > max_bytes:
        raise PayloadError("text_too_large")
    return redacted



_SENSITIVE_KEY = re.compile(
    r"(?i)(?:^|[_-])(?:authorization|api[_-]?key|access[_-]?token|"
    r"session[_-]?token|client[_-]?secret|refresh[_-]?token|password|"
    r"credentials?|secret[_-]?key|private[_-]?key|token|secret)(?:$|[_-])"
)


def sensitive_key(value: str) -> bool:
    return bool(_SENSITIVE_KEY.search(value))

def strict_json(value: str) -> Any:
    def pairs(items):
        result = {}
        for key, child in items:
            if key in result:
                raise PayloadError("duplicate_json_key")
            result[key] = child
        return result

    return json.loads(value, object_pairs_hook=pairs)



def check_shape(value: Any, *, max_depth: int, max_records: int,
                before_children: bool = False) -> None:
    records = 0

    def visit(item: Any, depth: int) -> None:
        nonlocal records
        if depth > max_depth:
            raise PayloadError("depth_limit")
        if isinstance(item, dict):
            records += len(item)
            if before_children and records > max_records:
                raise PayloadError("record_limit")
            for key, child in item.items():
                if not isinstance(key, str):
                    raise PayloadError("malformed_payload")
                visit(child, depth + 1)
        elif isinstance(item, list):
            records += len(item)
            if before_children and records > max_records:
                raise PayloadError("record_limit")
            for child in item:
                visit(child, depth + 1)
        elif item is not None and not isinstance(item, (str, int, float, bool)):
            raise PayloadError("malformed_payload")
        elif isinstance(item, float) and not math.isfinite(item):
            raise PayloadError("malformed_payload")
        if records > max_records:
            raise PayloadError("record_limit")

    visit(value, 1)

def sanitize_tree(value: Any, *, max_bytes: int) -> tuple[Any, bool]:
    if isinstance(value, str):
        cleaned = redact(value, max_bytes)
        return cleaned, cleaned != value
    if isinstance(value, list):
        pairs = [sanitize_tree(item, max_bytes=max_bytes) for item in value]
        return [item for item, _ in pairs], any(changed for _, changed in pairs)
    if isinstance(value, dict):
        sanitized = {}
        changed = False
        for key, item in value.items():
            safe_key = redact(key, max_bytes)
            if sensitive_key(key):
                safe_key = "[REDACTED]"
                item = "[REDACTED]"
                changed = True
            if safe_key in sanitized:
                raise PayloadError("redacted_key_collision")
            safe_item, item_changed = sanitize_tree(item, max_bytes=max_bytes)
            sanitized[safe_key] = safe_item
            changed = changed or safe_key != key or item_changed
        return sanitized, changed
    return value, False
